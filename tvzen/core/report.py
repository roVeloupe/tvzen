def to_html(plan: Plan, res: ApplyResult | None = None) -> str:
    groups: dict[str, list] = {}
    for v in plan.targets:
        groups.setdefault(v.category.value, []).append(v)
    cards = []
    for cat, items in sorted(groups.items()):
        rows = "".join(
            f"<tr><td>{html.escape(v.package)}</td>"
            f"<td><span class='badge {v.risk.value}'>{RISK_LABEL[v.risk.value]}</span></td>"
            f"<td class='score'>{v.score}</td><td>{html.escape(v.reason)}</td></tr>"
            for v in items)
        cards.append(
            f"<div class='card'><b>{CATEGORY_LABEL.get(cat, cat)}</b>（{len(items)}）"
            f"<table><tr><th>包名</th><th>风险</th><th>分数</th><th>命中原因</th></tr>{rows}</table></div>")
    applied = f"<div class='card'>✅ 已禁用 {len(res.applied)} 个包" + \
              (f"，快照: <code>{html.escape(res.snapshot_path)}</code>" if res.snapshot_path else "") + \
              "</div>" if res else ""
    return _HTML_TEMPLATE.format(
        model=html.escape(plan.model or plan.device),
        when=time.strftime("%Y-%m-%d %H:%M"),
        total=plan.total_packages, n=plan.count,
        cards="".join(cards) + applied)


def save_report(plan: Plan, path: str | Path, fmt: str = "html",
                res: ApplyResult | None = None) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    content = {"html": to_html, "json": to_json, "text": render_plan}[fmt](plan, res) \
        if res or fmt != "text" else render_plan(plan)
    p.write_text(content, encoding="utf-8")
    return p
