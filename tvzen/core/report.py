"""报告生成：终端表格 + JSON + 可分享的 HTML 净化报告。"""

from __future__ import annotations

import html
import json
import time
from dataclasses import asdict
from pathlib import Path

from .adb import Device
from .engine import ApplyResult, Plan
from .policies import ScanResult

CATEGORY_LABEL = {
    "ads": "📺 广告组件",
    "bloat": "🗑️ 预装推广",
    "telemetry": "📡 遥测统计",
    "promo": "🛍️ 推广服务",
    "unknown": "❓ 未分类",
}

RISK_LABEL = {"safe": "安全", "caution": "谨慎", "critical": "关键"}


def render_plan(plan: Plan, device: Device | None = None) -> str:
    lines: list[str] = []
    dev = f"{plan.model} ({plan.device})" if plan.model else plan.device
    lines.append(f"🧘 TVZen 净化计划 · {dev}")
    lines.append(f"   设备共 {plan.total_packages} 个包，命中 {plan.count} 个可净化目标")
    if not plan.targets:
        lines.append("   ✅ 未发现可净化项（设备已很干净）")
        return "\n".join(lines)
    lines.append("")
    lines.append(f"   {'包名':<52} {'类别':<12} {'风险':<6} 分数")
    lines.append("   " + "-" * 86)
    for v in plan.targets:
        lines.append(
            f"   {v.package:<52} {CATEGORY_LABEL[v.category.value]:<12} "
            f"{RISK_LABEL[v.risk.value]:<6} {v.score}")
    s = plan.summary()
    lines.append("")
    lines.append("   汇总: " + " · ".join(f"{CATEGORY_LABEL[k]} {v}" for k, v in s.items()))
    return "\n".join(lines)


def render_result(plan: Plan, res: ApplyResult) -> str:
    lines = [f"✅ 净化完成：禁用 {len(res.applied)} 个包"]
    if res.failed:
        lines.append(f"⚠️  {len(res.failed)} 个包失败: {', '.join(res.failed)}")
    if res.snapshot_path:
        lines.append(f"💾 快照已保存: {res.snapshot_path}")
        lines.append("   随时可用 `tvzen rollback` 一键还原")
    return "\n".join(lines)


def to_json(plan: Plan, res: ApplyResult | None = None) -> str:
    payload = {
        "tool": "tvzen",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "device": plan.device,
        "model": plan.model,
        "total_packages": plan.total_packages,
        "targets": [asdict(v) | {"category": v.category.value, "risk": v.risk.value}
                    for v in plan.targets],
        "applied": res.applied if res else [],
        "failed": res.failed if res else [],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)


